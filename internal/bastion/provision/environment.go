func (em *EnvironmentManager) addOCFPConfig(content *strings.Builder) {
	content.WriteString("# OCFP bloc configuration\n")
	content.WriteString("if [ -n \"$OCFP_BLOC\" ]; then\n")
	content.WriteString("    export OCFP_BLOC=\"$OCFP_BLOC\"\n")
	content.WriteString("fi\n")
	content.WriteString("\n")
}

func (em *EnvironmentManager) addProviderConfig(content *strings.Builder) {
	content.WriteString("# Provider configuration\n")
	content.WriteString("if [ -n \"$OCFP_PROVIDER\" ]; then\n")
	content.WriteString("    export OCFP_PROVIDER=\"$OCFP_PROVIDER\"\n")
	content.WriteString("    \n")
	content.WriteString("    case \"$OCFP_PROVIDER\" in\n")
	em.addStackitProviderConfig(content)
	em.addAWSProviderConfig(content)
	em.addAzureProviderConfig(content)
	em.addGCPProviderConfig(content)
	content.WriteString("    esac\n")
	content.WriteString("fi\n")
	content.WriteString("\n")
}

