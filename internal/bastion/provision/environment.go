// EnvironmentManager handles shell and system environment configuration.
type EnvironmentManager struct {
	config   *config.Config
	provider string
	log      logger.Logger
}

// NewEnvironmentManager creates a new environment manager.
func NewEnvironmentManager(provider string, cfg *config.Config) *EnvironmentManager {
	return &EnvironmentManager{
		config:   cfg,
		provider: provider,
		log:      logger.Get(),
	}
}

// GetSystemEnvironmentVarsForPreview exposes the key/value set for previews.
func (em *EnvironmentManager) GetSystemEnvironmentVarsForPreview() map[string]string {
	return em.getSystemEnvironmentVars()
}

// GenerateShellEnvironmentScript generates .bashrc configuration.
func (em *EnvironmentManager) GenerateShellEnvironmentScript(_ctx context.Context) string {
	// Preallocate a sensible capacity; mostly fixed-size content
	lines := make([]string, 0, scriptBufferEnvironmentBase)

	lines = append(lines, "# Shell environment configuration")
	lines = append(lines, "")

	// Generate bashrc additions
	bashrcContent := em.generateBashrcAdditions()

	lines = append(lines, "# Check if shell environment already configured")
	lines = append(lines, `if grep -q "OCFP Environment Configuration" "$HOME/.bashrc" 2>/dev/null; then`)
	lines = append(lines, "    log_success 'Shell environment already configured'")
	lines = append(lines, "else")
	lines = append(lines, "    log_info 'Configuring shell environment'")
	lines = append(lines, "    cat >> \"$HOME/.bashrc\" << 'BASHRC_EOF'")
	lines = append(lines, bashrcContent)
	lines = append(lines, "BASHRC_EOF")
	lines = append(lines, "    log_success 'Shell environment configured'")
	lines = append(lines, "fi")
	lines = append(lines, "")

	return strings.Join(lines, "\n")
}

// GenerateSystemEnvironmentScript generates /etc/environment and /etc/profile.d setup.
func (em *EnvironmentManager) GenerateSystemEnvironmentScript(_ctx context.Context) string {
	envVars := em.getSystemEnvironmentVars()
	lines := make([]string, 0, scriptBufferEnvironment+scriptBufferEnvironmentPerItem*len(envVars))

	lines = append(lines, "# System environment configuration")
	lines = append(lines, "")

	lines = append(lines, em.generateEnvironmentGuardClause()...)
	lines = append(lines, em.generateEtcEnvironmentUpdate(envVars)...)
	lines = append(lines, em.generateProfileDScript(envVars)...)

	return strings.Join(lines, "\n")
}

// generateBashrcAdditions creates the bashrc configuration content.
func (em *EnvironmentManager) generateBashrcAdditions() string {
	var content strings.Builder

	em.addBasicEnvironmentConfig(&content)
	em.addEditorConfig(&content)
	em.addAliases(&content)
	em.addOCFPConfig(&content)
	em.addProviderConfig(&content)
	em.addToolConfigurations(&content)

	return content.String()
}

func (em *EnvironmentManager) generateEnvironmentGuardClause() []string {
	return []string{
		"if [ -n \"${OCFP_BLOC:-}\" ]; then",
		"",
	}
}

func (em *EnvironmentManager) generateEtcEnvironmentUpdate(envVars map[string]string) []string {
	lines := make([]string, 0, 8+len(envVars)+len(envVars)+1+1+len(envVars)+1)
	lines = append(lines,
		"    # Update /etc/environment atomically (merge desired keys)",
		"    TMP_ENV=$(mktemp /tmp/ocfp-environment.XXXXXX)",
		"    if [ -f /etc/environment ]; then",
		"        sudo cp /etc/environment \"$TMP_ENV\"",
		"        sudo chown $(whoami) \"$TMP_ENV\"",
		"    else",
		"        : > \"$TMP_ENV\"",
		"    fi",
	)

	for key := range envVars {
		lines = append(lines, fmt.Sprintf("    sed -i -E '/^%s=/d' \"$TMP_ENV\"", key))
	}

	for key, value := range envVars {
		desired := fmt.Sprintf("%s=%s", key, value)
		lines = append(lines, fmt.Sprintf("    echo '%s' >> \"$TMP_ENV\"", desired))
	}

	lines = append(lines, "    sudo install -m 0644 \"$TMP_ENV\" /etc/environment")
	lines = append(lines, "    rm -f \"$TMP_ENV\"")

	for key, value := range envVars {
		desired := fmt.Sprintf("%s=%s", key, value)
		lines = append(lines, fmt.Sprintf("    grep -qF '%s' /etc/environment && log_success '%s set in /etc/environment' || log_warning '%s missing in /etc/environment'", desired, key, key))
	}

	lines = append(lines, "    ")

	return lines
}

func (em *EnvironmentManager) generateProfileDScript(envVars map[string]string) []string {
	lines := make([]string, 0, 7+len(envVars)+12) //nolint:mnd
	lines = append(lines,
		"    # Create /etc/profile.d/ocfp.sh (atomic write)",
		"    log_info 'Creating /etc/profile.d/ocfp.sh'",
		"    sudo tee /tmp/ocfp_profile.sh >/dev/null << 'PROFILE_EOF'",
		"#!/bin/sh",
		"# OCFP environment variables",
		"# Generated by ocfp bastion provisioning",
		"",
	)

	// Source Linuxbrew so brew-installed binaries are on PATH for login shells
	lines = append(lines,
		"# Linuxbrew environment",
		`if [ -x /home/linuxbrew/.linuxbrew/bin/brew ]; then`,
		`    eval "$(/home/linuxbrew/.linuxbrew/bin/brew shellenv)"`,
		"fi",
		"",
	)

	for key, value := range envVars {
		lines = append(lines, fmt.Sprintf("export %s='%s'", key, value))
	}

	lines = append(lines, "PROFILE_EOF")
	lines = append(lines, "    sudo install -m 0644 /tmp/ocfp_profile.sh /etc/profile.d/ocfp.sh")
	lines = append(lines, "    # Verify write")
	lines = append(lines, "    if [ -f /etc/profile.d/ocfp.sh ] && grep -q 'OCFP environment variables' /etc/profile.d/ocfp.sh; then")
	lines = append(lines, "        log_success '/etc/profile.d/ocfp.sh created'")
	lines = append(lines, "    else")
	lines = append(lines, "        log_error 'Failed to create /etc/profile.d/ocfp.sh'")
	lines = append(lines, "    fi")
	lines = append(lines, "else")
	lines = append(lines, "    log_info 'No OCFP_BLOC provided, skipping system environment setup'")
	lines = append(lines, "fi")
	lines = append(lines, "")

	return lines
}

func (em *EnvironmentManager) addBasicEnvironmentConfig(content *strings.Builder) {
	content.WriteString("\n# OCFP Environment Configuration\n")
	content.WriteString("export OCFP_ROOT=\"$HOME/ocfp\"\n")
	content.WriteString("export OCFP_CLI=\"$HOME/ocfp/cli\"\n")
	content.WriteString("export DEPLOYMENTS_DIR=\"$HOME/ocfp/deployments\"\n")
	content.WriteString("export RELEASES_DIR=\"$HOME/ocfp/releases\"\n")
	content.WriteString("export ARTIFACTS_DIR=\"$HOME/ocfp/artifacts\"\n")
	content.WriteString("export PATH=\"$HOME/bin:$PATH\"\n")
	content.WriteString("# Linuxbrew environment\n")
	content.WriteString("eval \"$(/home/linuxbrew/.linuxbrew/bin/brew shellenv)\"\n")
	content.WriteString("\n")
}

