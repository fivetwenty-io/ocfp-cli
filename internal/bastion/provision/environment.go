func (em *EnvironmentManager) addToolConfigurations(content *strings.Builder) {
	// NVM configuration
	content.WriteString("# NVM configuration\n")
	content.WriteString("if [ -f \"$HOME/.nvm/nvm.sh\" ]; then\n")
	content.WriteString("    source \"$HOME/.nvm/nvm.sh\"\n")
	content.WriteString("    [ -s \"$HOME/.nvm/bash_completion\" ] && source \"$HOME/.nvm/bash_completion\"\n")
	content.WriteString("fi\n")
	content.WriteString("\n")

	// Bun configuration
	content.WriteString("# Bun configuration\n")
	content.WriteString("if [ -d \"$HOME/.bun\" ]; then\n")
	content.WriteString("    export BUN_INSTALL=\"$HOME/.bun\"\n")
	content.WriteString("    export PATH=\"$BUN_INSTALL/bin:$PATH\"\n")
	content.WriteString("fi\n")
	content.WriteString("\n")

	// Go version pinning (keg-only formula needs explicit PATH)
	content.WriteString("# Go (brew keg-only versioned formula)\n")
	content.WriteString("if [ -d \"$(brew --prefix)/opt/go@1.24/bin\" ] 2>/dev/null; then\n")
	content.WriteString("    export PATH=\"$(brew --prefix)/opt/go@1.24/bin:$PATH\"\n")
	content.WriteString("fi\n")
	content.WriteString("\n")
}

// getSystemEnvironmentVars returns environment variables for system configuration.
func (em *EnvironmentManager) getSystemEnvironmentVars() map[string]string {
	vars := map[string]string{
		"OCFP_BLOC":           em.config.Name,
		"OCFP_PROVIDER":       em.provider,
		"GENESIS_ENVIRONMENT": em.config.Name,
	}

	// Add provider-specific variables from config
	switch em.provider {
	case providerStackit:
		if em.config.ProjectID != "" {
			vars["STACKIT_PROJECT_ID"] = em.config.ProjectID
		}

		if em.config.OrgID != "" {
			vars["STACKIT_ORG_ID"] = em.config.OrgID
		}

		if em.config.Region != "" {
			vars["STACKIT_REGION"] = em.config.Region
		}
	case providerAWS:
		if em.config.AccessKeyID != "" {
			vars["AWS_ACCESS_KEY_ID"] = em.config.AccessKeyID
		}

		if em.config.SecretAccessKey != "" {
			vars["AWS_SECRET_ACCESS_KEY"] = em.config.SecretAccessKey
		}

		if em.config.Region != "" {
			vars["AWS_DEFAULT_REGION"] = em.config.Region
		}
	case providerAzure:
		if em.config.SubscriptionID != "" {
			vars["AZURE_SUBSCRIPTION_ID"] = em.config.SubscriptionID
		}

		if em.config.TenantID != "" {
			vars["AZURE_TENANT_ID"] = em.config.TenantID
		}

		if em.config.ClientID != "" {
			vars["AZURE_CLIENT_ID"] = em.config.ClientID
		}
	case providerGCP:
		if em.config.ProjectID != "" {
			vars["GCP_PROJECT_ID"] = em.config.ProjectID
		}
	}

	return vars
}
